export function getLemanaShopping(guide) {
  const source = [
    guide && guide.title,
    guide && guide.summary,
    guide && guide.material,
    guide && guide.task,
    ...(guide && guide.tags ? guide.tags : []),
  ].filter(Boolean).join(' ')

  const ids = []
  for (const rule of GUIDE_PRODUCT_RULES) {
    if (rule.test.test(source)) ids.push(...rule.ids)
  }
  ids.push(...(TASK_PRODUCT_IDS[guide.task] || []))

  const seen = new Set()
  const items = []
  const addById = (id) => {
    const item = PRODUCT_LIBRARY[id] || VERIFIED[id]
    if (!item || seen.has(item.title) || items.length >= 8) return
    seen.add(item.title)
    items.push({ id, ...item })
  }

  ids.forEach(addById)

  if (items.length < 4) {
    for (const material of guide.materials || []) {
      const title = String(material)
      if (seen.has(title)) continue
      seen.add(title)
      items.push({
        id: 'material-' + items.length,
        title,
        spec: 'Поиск по каталогу Лемана ПРО. Перед покупкой сверь размер, материал основания и требования инструкции.',
        kind: 'По списку статьи',
        url: lemanaSearch(title),
      })
      if (items.length >= 4) break
    }
  }

  if (items.length < 4) {
    for (const id of CATEGORY_PRODUCT_IDS[guide.category] || []) {
      addById(id)
      if (items.length >= 4) break
    }
  }

  return items
}

