function resolveSources(category, sourceIds) {
  const ids = sourceIds?.length ? sourceIds : CATEGORY_KITS[category]?.sourceIds || []
  return ids.map((id) => DOM_SOURCE_BY_ID[id]).filter(Boolean)
}

function enrichBaseGuide(guide) {
  return {
    ...guide,
    sources: guide.sources?.length ? guide.sources : resolveSources(guide.category),
  }
}

